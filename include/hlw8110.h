/**
 * @file    hlw8110.h
 * @brief   HLW8110 / HLW8112 power-metering IC driver (UART, STM32 HAL + FreeRTOS).
 *
 * The driver reads voltage, current, active/apparent power, power factor, line
 * frequency and phase angle from the chip, converts them with the factory
 * coefficients stored in the chip ("calibration-free" method, datasheet
 * chapter 10) and publishes a thread-safe snapshot refreshed by a background
 * FreeRTOS task.
 *
 * @par Minimal usage
 * @code
 * static HLW8110_Handle_t hlw;                       // MUST be static / zero-initialised
 *
 * void app_task(void *arg)                           // run after the scheduler started
 * {
 *     HLW8110_Config_t cfg;
 *     HLW8110_ConfigDefault(&cfg, &huart2);          // chip UART
 *     cfg.k1_current = 1.0f;                         // shunt: 1 mOhm (R001)
 *     cfg.k2_voltage = HLW8110_CalcK2(1000000.0f, 1650.0f); // 5x200k top, 1.65k bottom
 *
 *     HLW8110_Init(&hlw, &cfg);
 *     while (HLW8110_AppInit(&hlw) != HLW8110_OK) vTaskDelay(pdMS_TO_TICKS(1000));
 *     HLW8110_StartTask(&hlw, "HLW8110", 1024, tskIDLE_PRIORITY + 2, cfg.measurement_period_ticks);
 *
 *     for (;;) {
 *         HLW8110_Measurements_t m;
 *         if (HLW8110_GetMeasurements(&hlw, &m) == HLW8110_OK) {
 *             // m.voltage_v, m.current_a, m.active_power_w, m.power_factor ...
 *         }
 *         vTaskDelay(pdMS_TO_TICKS(500));
 *     }
 * }
 *
 * // Forward the HAL callbacks (see @ref hlw8110_callbacks):
 * void HAL_UART_RxCpltCallback(UART_HandleTypeDef *h) { HLW8110_UART_RxCpltCallback(&hlw, h); }
 * void HAL_UART_ErrorCallback (UART_HandleTypeDef *h) { HLW8110_UART_ErrorCallback (&hlw, h); }
 * @endcode
 *
 * @par Porting
 * The driver needs the HAL header of your MCU family. By default it includes
 * `"main.h"` (generated by STM32CubeMX). Define `HLW8110_HAL_HEADER` (for
 * example `-DHLW8110_HAL_HEADER=\"stm32f4xx_hal.h\"`) to change it.
 *
 * @version 1.1.0
 * @copyright MIT License (see LICENSE)
 */
